package io.github.yassinessadi.ecopass

object RecordType {

  val NULL_RECORD = 0
  val SYSTEM_RECORD_DUPLICATE = 1
  val DELETED_RECORD = 2
  val SYSTEM_RESERVED = 3
  val NORMAL_USER_DATA = 4
  val REDUCED_USER_DATA = 5
  val POINTER_RECORD = 6
  val USER_DATA_RECORD = 7
  val REDUCED_USER_DATA_REFERENCED_BY_POINTER = 8
  val RESERVED_FOR_FUTURE_USE = 9
  val MID_TRANSACTION_USER_RECORD = 10
  val MID_TRANSACTION_REDUCED_USER_RECORD = 11
  val MID_TRANSACTION_USER_RECORD_REFERENCED = 12
  val MID_TRANSACTION_REDUCED_USER_RECORD_REFERENCED = 13

  def nameOf(status: Int): String = status match {
    case NULL_RECORD => "NULL_RECORD"
    case SYSTEM_RECORD_DUPLICATE => "SYSTEM_RECORD_DUPLICATE"
    case DELETED_RECORD => "DELETED_RECORD"
    case SYSTEM_RESERVED => "SYSTEM_RESERVED"
    case NORMAL_USER_DATA => "NORMAL_USER_DATA"
    case REDUCED_USER_DATA => "REDUCED_USER_DATA"
    case POINTER_RECORD => "POINTER_RECORD"
    case USER_DATA_RECORD => "USER_DATA_RECORD"
    case REDUCED_USER_DATA_REFERENCED_BY_POINTER =>
      "REDUCED_USER_DATA_REFERENCED_BY_POINTER"
    case RESERVED_FOR_FUTURE_USE => "RESERVED_FOR_FUTURE_USE"
    case MID_TRANSACTION_USER_RECORD => "MID_TRANSACTION_USER_RECORD"
    case MID_TRANSACTION_REDUCED_USER_RECORD =>
      "MID_TRANSACTION_REDUCED_USER_RECORD"
    case MID_TRANSACTION_USER_RECORD_REFERENCED =>
      "MID_TRANSACTION_USER_RECORD_REFERENCED"
    case MID_TRANSACTION_REDUCED_USER_RECORD_REFERENCED =>
      "MID_TRANSACTION_REDUCED_USER_RECORD_REFERENCED"
    case other => s"UNKNOWN_$other"
  }

  def isKnown(status: Int): Boolean =
    status >= NULL_RECORD &&
      status <= MID_TRANSACTION_REDUCED_USER_RECORD_REFERENCED
}